    local function registerPrompt(p)
        if prompts[p] then return end
        prompts[p] = true
        p:SetAttribute("RH_dist", p.MaxActivationDistance)
        p:SetAttribute("RH_hold", p.HoldDuration)
        applyPrompt(p)
        local model = p:FindFirstAncestorOfClass("Model")
        -- Sofás / asientos: Auto Interact los ignora (te sentaba y perdías tiempo)
        do
            local txt = (p.ActionText or ""):lower()
            local isCouch = txt:find("sit", 1, true) or txt:find("sentar", 1, true)
            local cur, depth = p.Parent, 0
            while not isCouch and cur and cur ~= workspace and depth < 4 do
                local n = cur.Name:lower()
                if n:find("couch", 1, true) or n:find("sofa", 1, true) or n:find("sofá", 1, true)
                    or n:find("armchair", 1, true) then
                    isCouch = true
                end
                cur = cur.Parent
                depth = depth + 1
            end
            if isCouch then couchPrompts[p] = true end
        end
        if model then
            if p.Name == "ModulePrompt" then
                cand("Item", model, Color3.fromRGB(120, 220, 255), model.Name, true)
            end
            if (p.ActionText or ""):lower():find("hide") then
                cand("Hide", model, Color3.fromRGB(150, 255, 150), "Hide", true)
                hidePrompts[p] = model
            end
            if model.Name == "GoldPile" or model.Name == "MoneyBag" then
                lootPrompts[p] = true
            end
        end
        p.AncestryChanged:Connect(function()
            if not p:IsDescendantOf(workspace) then
                prompts[p] = nil
                lootPrompts[p] = nil
                couchPrompts[p] = nil
                hidePrompts[p] = nil
            end
        end)
    end

