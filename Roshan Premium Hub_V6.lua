            pcall(function() if setclipboard then setclipboard(CONFIG.Discord) end end)
            notify("📋 Discord copiado", "ok", 2)
        end, Color3.fromRGB(88, 101, 242))
        Label(pCred, "Gracias por usar el hub 💜", Color3.fromRGB(200, 180, 255))
    end

    ------------------------------------------------------------------
    -- CONFIG
    ------------------------------------------------------------------
    do
        Section(pCfg, "Idioma")
        local langBtn = Button(pCfg, function() return "🌐 " .. tr("Idioma") .. ": " .. LANG_NAMES[Lang] end, function()
            setLang(nextLang())
            notify("🌐 Idioma: %s", "ok", 2, LANG_NAMES[Lang])
        end)

        -- Temas
        local THEMES = {
            { "Morado", Color3.fromRGB(170, 70, 255) },
            { "Rojo", Color3.fromRGB(235, 60, 70) },
            { "Azul", Color3.fromRGB(70, 140, 255) },
            { "Verde", Color3.fromRGB(70, 210, 120) },
            { "Dorado", Color3.fromRGB(255, 200, 60), true },
            { "Rosa", Color3.fromRGB(255, 100, 190), true },
        }
        local themeIdx = 1
        S.themeColor = THEMES[1][2]
        Section(pCfg, "Tema")
        Button(pCfg, function() return "🎨 " .. tr("Tema") .. ": " .. tr(THEMES[themeIdx][1]) end, function()
            local nxt = themeIdx % #THEMES + 1
            if THEMES[nxt][3] and not isVip then
                -- salta los temas VIP si no tiene acceso
                nxt = 1
                notify("🔒 Tema exclusivo VIP", "warn", 2)
            end
            themeIdx = nxt
            S.themeColor = THEMES[themeIdx][2]
            if not rainbowOn then setAccent(S.themeColor) end
            notify("🎨 Tema: %s", "ok", 2, tr(THEMES[themeIdx][1]))
        end)

        Section(pCfg, "Sonido")
        Toggle(pCfg, "Sonidos", true, function(on) S.sound = on end)
        Slider(pCfg, "Volumen", 0, 10, 6, function(v) S.volume = v / 10 end)
        Button(pCfg, "🔔 Probar notificación", function()
            notify("🔔 Prueba de sonido y alerta", "danger", 3)
        end)

        Section(pCfg, "Interfaz")
        Slider(pCfg, "Escala de UI", 70, 130, 100, function(v)
            S.uiScalePct = v
            winScale.Scale = v / 100
        end)
        Slider(pCfg, "Duración de avisos", 50, 200, 100, function(v) S.toastPct = v end)
        Slider(pCfg, "Máx. avisos en pantalla", 1, 6, 4, function(v) S.maxToasts = v end)
        Toggle(pCfg, "FPS/Ping en pantalla", false, function(on)
            S.hud = on
            hudLabel.Visible = on
        end)
        Toggle(pCfg, "Sin sofás en Auto Interact", true, function(on) S.skipCouch = on end)
        Toggle(pCfg, "Mostrar avisos de jugadores staff", true, function(on) S.staffAlerts = on end)

        Section(pCfg, "Sistema")
        Toggle(pCfg, "Debug (consola)", false, function(on) S.debug = on end)
        Button(pCfg, "Hide UI", function() setOpen(false) end)
        Button(pCfg, "🔄 Rejoin", function()
            pcall(function()
                local TS = game:GetService("TeleportService")
                if #Players:GetPlayers() <= 1 then
                    LocalPlayer:Kick("\nRejoining...")
                    task.wait()
                    TS:Teleport(game.PlaceId, LocalPlayer)
                else
                    TS:TeleportToPlaceInstance(game.PlaceId, game.JobId, LocalPlayer)
                end
            end)
        end)
        Button(pCfg, "📋 Copy JobId", function()
            pcall(function() if setclipboard then setclipboard(tostring(game.JobId)) end end)
            notify("📋 Info copiada al portapapeles", "ok", 2)
        end)
        Button(pCfg, "Reset All Settings", function()
            for _, set in ipairs(setters) do set(false) end
            S.reach, S.speedValue, S.fov = 0, 16, nil
            refreshPrompts()
            notify("✅ Ajustes reseteados", "ok", 2)
        end)

        Button(pCfg, "Destruir script", function()
            alive = false
            for _, c in ipairs(connections) do pcall(function() c:Disconnect() end) end
            for _, fn in ipairs(cleanups) do pcall(fn) end
            for k in pairs(S) do
                if type(S[k]) == "boolean" then S[k] = false end
            end
            for kind in pairs(espObjs) do clearESP(kind) end
            for p in pairs(prompts) do
                if p.Parent then
                    local d, h = p:GetAttribute("RH_dist"), p:GetAttribute("RH_hold")
                    if d then p.MaxActivationDistance = d end
                    if h then p.HoldDuration = h end
                end
            end
            gui:Destroy()
            getgenv().RoshanHubLoaded = false
        end, Color3.fromRGB(120, 30, 50))

        Label(pCfg, "Toca R (botón flotante) para abrir/cerrar. En PC: RightShift.")
    end

    ------------------------------------------------------------------
    -- Arranque
    ------------------------------------------------------------------
    selectTab("Principal")
    if role then
        notify("⭐ Bienvenido %s %s", "ok", 5, role, LocalPlayer.Name)
    else
        notify("✅ %s cargado", "ok", 4, CONFIG.Name)
    end
end

