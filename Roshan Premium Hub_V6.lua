local function pulse(st, c1, c2)
    st.Color = c1
    local tw = TweenService:Create(st, TweenInfo.new(1.4, Enum.EasingStyle.Sine,
        Enum.EasingDirection.InOut, -1, true), { Color = c2 })
    tw:Play()
    return tw
end

