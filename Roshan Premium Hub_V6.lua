    local function onEntity(inst)
        local def = ENT[entKey(inst.Name)]
        if not def then return end
        if esp.Entity then addESP("Entity", inst, def.c, def.n) end
        if not def.silent and not seenEnt[inst] then
            seenEnt[inst] = true
            activeEnts[inst] = def
            stats.ents = stats.ents + 1
            if S.autoHide and S.hideNames[def.n] and S.onDanger then pcall(S.onDanger, def) end
            local now = tick()
            if S.notify and (not lastNotif[def.n] or now - lastNotif[def.n] > (def.cd or 3)) then
                lastNotif[def.n] = now
                notify(def.m, def.k, 6)
            end
        end
        if not hooked[inst] then
            hooked[inst] = true
            inst.AncestryChanged:Connect(function()
                if not inst:IsDescendantOf(workspace) then
                    activeEnts[inst] = nil
                    if def.pass and alive and S.notify then
                        -- Seek crea muchas partes: solo avisamos cuando ya no queda ninguna viva
                        for other, od in pairs(activeEnts) do
                            if od.n == def.n and other.Parent then return end
                        end
